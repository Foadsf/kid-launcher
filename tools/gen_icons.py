#!/usr/bin/env python3
"""Generate the launcher's icon vector drawables into app/src/main/res/drawable/.

The icons are original artwork made of plain circles, rounded rectangles and polygons, so
they are written as code rather than drawn in an editor: shapes stay exact, colours come from
one palette, and a change is a reviewable diff. Released with the app (no third-party art).

    python3 tools/gen_icons.py

Only features that AGP's build-time vector-to-PNG rasteriser supports are used (solid fills,
strokes, groups with rotation). VectorDrawable itself needs API 21; on the API 19 phone the
generated PNGs are what is shown.
"""
import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"

# Palette - kept in step with res/values/colors.xml.
PINK, PINK_D = "#FFFF8FA3", "#FFE8607E"
YELLOW, YELLOW_D = "#FFFFD166", "#FFF0A830"
LILAC, LILAC_D = "#FFB79CFF", "#FF8466E0"
BLUE, BLUE_D = "#FF7CC8FF", "#FF3F95E0"
MINT, MINT_D = "#FF7EE0B5", "#FF34B57F"
PEACH, PEACH_D = "#FFFFAD7A", "#FFEE7F45"
PLUM = "#FF5B3E8C"
WHITE = "#FFFFFFFF"
SKYPALE = "#FFDDF2FF"


def f(x):
    return f"{x:.2f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
    return (f"M{f(cx - r)},{f(cy)} a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0 "
            f"a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0 Z")


def rrect(x0, y0, x1, y1, r):
    return (f"M{f(x0 + r)},{f(y0)} L{f(x1 - r)},{f(y0)} A{f(r)},{f(r)} 0 0 1 {f(x1)},{f(y0 + r)} "
            f"L{f(x1)},{f(y1 - r)} A{f(r)},{f(r)} 0 0 1 {f(x1 - r)},{f(y1)} "
            f"L{f(x0 + r)},{f(y1)} A{f(r)},{f(r)} 0 0 1 {f(x0)},{f(y1 - r)} "
            f"L{f(x0)},{f(y0 + r)} A{f(r)},{f(r)} 0 0 1 {f(x0 + r)},{f(y0)} Z")


def poly(*pts):
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in pts) + " Z"


def star(cx, cy, r_out, r_in, n=5, rot=-90):
    pts = []
    for i in range(2 * n):
        r = r_out if i % 2 == 0 else r_in
        a = math.radians(rot + i * 180 / n)
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return poly(*pts)


def heart(cx, cy, s):
    """Heart centred on (cx, cy), roughly s wide."""
    k = s / 2
    return (f"M{f(cx)},{f(cy + k * 0.95)} "
            f"C{f(cx - k * 0.2)},{f(cy + k * 0.75)} {f(cx - k)},{f(cy + k * 0.2)} {f(cx - k)},{f(cy - k * 0.3)} "
            f"C{f(cx - k)},{f(cy - k * 0.85)} {f(cx - k * 0.25)},{f(cy - k * 1.0)} {f(cx)},{f(cy - k * 0.45)} "
            f"C{f(cx + k * 0.25)},{f(cy - k * 1.0)} {f(cx + k)},{f(cy - k * 0.85)} {f(cx + k)},{f(cy - k * 0.3)} "
            f"C{f(cx + k)},{f(cy + k * 0.2)} {f(cx + k * 0.2)},{f(cy + k * 0.75)} {f(cx)},{f(cy + k * 0.95)} Z")


def sparkle(cx, cy, r):
    """Four-pointed twinkle."""
    return star(cx, cy, r, r * 0.32, n=4, rot=-90)


def path(d, fill=None, stroke=None, width=0, cap="round", join="round"):
    a = [f'android:pathData="{d}"']
    if fill:
        a.append(f'android:fillColor="{fill}"')
    if stroke:
        a.append(f'android:strokeColor="{stroke}" android:strokeWidth="{f(width)}" '
                 f'android:strokeLineCap="{cap}" android:strokeLineJoin="{join}"')
    return "    <path " + " ".join(a) + "/>"


def group(rot, px, py, *children):
    inner = "\n".join("    " + c for c in children)
    return (f'    <group android:rotation="{f(rot)}" android:pivotX="{f(px)}" android:pivotY="{f(py)}">\n'
            f"{inner}\n    </group>")


def vector(name, size_dp, *children):
    body = "\n".join(children)
    xml = (f'<?xml version="1.0" encoding="utf-8"?>\n'
           f"<!-- Generated by tools/gen_icons.py - edit that, not this. -->\n"
           f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           f'    android:width="{size_dp}dp" android:height="{size_dp}dp"\n'
           f'    android:viewportWidth="100" android:viewportHeight="100">\n{body}\n</vector>\n')
    (OUT / f"{name}.xml").write_text(xml)


ICON_DP = 96  # drawn at ~90 dp on the phone; generating at 96 dp keeps the PNGs crisp

# Camera: chunky body, big friendly lens, yellow flash.
vector("ic_camera", ICON_DP,
       path(rrect(30, 18, 56, 34, 6), fill=PINK_D),
       path(rrect(62, 22, 78, 30, 4), fill=YELLOW_D),
       path(rrect(10, 28, 90, 82, 14), fill=PINK),
       path(poly((10, 44), (90, 44), (90, 50), (10, 50)), fill=PINK_D),
       path(circle(50, 56, 23), fill=WHITE),
       path(circle(50, 56, 18), fill=PLUM),
       path(circle(50, 56, 11), fill=BLUE),
       path(circle(44.5, 50.5, 4.5), fill=WHITE),
       path(circle(55, 61, 2), fill=WHITE),
       path(circle(79, 38, 4.5), fill=YELLOW))

# Photos: a framed picture with sky, sun and two green hills.
vector("ic_photos", ICON_DP,
       group(-6, 50, 50,
             path(rrect(12, 18, 88, 82, 10), fill=YELLOW_D),
             path(rrect(19, 25, 81, 75, 6), fill=SKYPALE),
             path(circle(64, 39, 7.5), fill=YELLOW),
             path("M19,62 Q32,44 46,58 Q58,46 81,60 L81,69 A6,6 0 0 1 75,75 L25,75 "
                  "A6,6 0 0 1 19,69 Z", fill=MINT),
             path("M19,69 Q40,58 62,75 L25,75 A6,6 0 0 1 19,69 Z", fill=MINT_D)))

# Music: two beamed notes with a twinkle.
vector("ic_music", ICON_DP,
       path(poly((38, 26), (82, 16), (82, 30), (38, 40)), fill=LILAC_D),
       path(rrect(38, 30, 45, 72, 2), fill=LILAC_D),
       path(rrect(75, 20, 82, 64, 2), fill=LILAC_D),
       group(-22, 33, 72, path(rrect(20, 62, 46, 82, 10), fill=LILAC_D)),
       group(-22, 70, 64, path(rrect(57, 54, 83, 74, 10), fill=LILAC_D)),
       path(circle(29, 69, 3), fill="#55FFFFFF"),
       path(circle(66, 61, 3), fill="#55FFFFFF"),
       path(sparkle(20, 30, 10), fill=YELLOW_D),
       path(heart(62, 84, 11), fill=PINK))

# Videos: a little TV with antennae and a big play button.
vector("ic_videos", ICON_DP,
       path("M50,26 L36,10 M50,26 L64,10", stroke=BLUE_D, width=4.5),
       path(circle(36, 10, 4), fill=YELLOW),
       path(circle(64, 10, 4), fill=YELLOW),
       path(rrect(10, 24, 90, 82, 14), fill=BLUE_D),
       path(rrect(18, 32, 82, 74, 8), fill=SKYPALE),
       path(poly((43, 42), (43, 64), (62, 53)), fill=PINK, stroke=PINK, width=6),
       path(rrect(24, 82, 36, 88, 3), fill=BLUE_D),
       path(rrect(64, 82, 76, 88, 3), fill=BLUE_D))

# Games: a chunky gamepad with a white d-pad and four candy buttons.
vector("ic_games", ICON_DP,
       path(sparkle(22, 22, 9), fill=YELLOW_D),
       path(sparkle(80, 18, 6), fill=PINK),
       path("M30,34 L70,34 C84,34 94,46 94,62 C94,76 86,84 78,84 C70,84 66,76 60,72 "
            "L40,72 C34,76 30,84 22,84 C14,84 6,76 6,62 C6,46 16,34 30,34 Z", fill=MINT_D),
       path(rrect(22, 46, 30, 66, 2.5), fill=WHITE),
       path(rrect(16, 52, 36, 60, 2.5), fill=WHITE),
       path(circle(72, 47, 5), fill=YELLOW),
       path(circle(72, 65, 5), fill=BLUE),
       path(circle(63, 56, 5), fill=PINK),
       path(circle(81, 56, 5), fill=LILAC),
       path(rrect(44, 48, 56, 53, 2.5), fill="#80FFFFFF"))

# "Back home" button on the Games screen: a pink house with a heart.
vector("ic_home", 48,
       path(poly((50, 14), (90, 48), (80, 48), (80, 86), (20, 86), (20, 48), (10, 48)),
            fill=PINK, stroke=PINK, width=8),
       path(heart(50, 64, 30), fill=WHITE))

# The app's own icon (shown in Android's "choose home" list): a heart-house on pink.
vector("ic_launcher", 48,
       path(rrect(4, 4, 96, 96, 22), fill=PINK),
       path(poly((50, 18), (84, 48), (76, 48), (76, 80), (24, 80), (24, 48), (16, 48)),
            fill=WHITE, stroke=WHITE, width=6),
       path(heart(50, 60, 26), fill=PINK_D),
       path(sparkle(80, 20, 9), fill=YELLOW))

# Small heart drawn after the greeting.
vector("ic_heart", 28, path(heart(50, 52, 84), fill=PINK_D))

print("wrote", sorted(p.name for p in OUT.glob("ic_*.xml")))
